# WGS84 -> LV95 approximate conversion (only valid for Switzerland)
def wgs84_to_lv95(lat, lon):
    """Approximate WGS84 to LV95 conversion. Returns (E, N) or (None, None) for non-CH."""
    if not (45.5 < lat < 48.0 and 5.5 < lon < 11.0):
        return None, None
    lat_aux = (lat * 3600 - 169028.66) / 10000
    lon_aux = (lon * 3600 - 26782.5) / 10000
    e = 2600072.37 + 211455.93 * lon_aux - 10938.51 * lon_aux * lat_aux - 0.36 * lon_aux * lat_aux**2 - 44.54 * lon_aux**3
    n = 1200147.07 + 308807.95 * lat_aux + 3745.25 * lon_aux**2 + 76.63 * lat_aux**2 - 194.56 * lon_aux**2 * lat_aux + 119.79 * lat_aux**3
    return round(e, 1), round(n, 1)


